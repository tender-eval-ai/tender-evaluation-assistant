"""Settings, authentication and the helpers every router shares.

Settings are read from the environment by `configure()`, which `backend.api` calls at
import (after loading `.env`) and which tests call again through
`importlib.reload(backend.api)` after changing DATA_DIR / INBOX_DIR / API_KEY. Routers
read them as `deps.PROJECTS`, `deps.API_KEY`, ... at call time, never by binding the
name at import, so a reconfiguration is seen everywhere.
"""
from __future__ import annotations

import json
import os
import re
import secrets
import threading
import time
from pathlib import Path

from fastapi import Header, HTTPException, UploadFile

from app.config import Config
from app.schemas import BidExtraction

DATA_DIR = Path("data")
PROJECTS = DATA_DIR / "projects"
API_KEY = ""
INBOX_DIR = Path("inbox")
GRAPH_DB_SCRATCH: str | None = None

DOCX_MIME = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
DEFAULT_USER = "anonymous"
_runner = None


def configure() -> None:
    """(Re)read the environment into the module's settings."""
    global DATA_DIR, PROJECTS, API_KEY, INBOX_DIR, GRAPH_DB_SCRATCH
    DATA_DIR = Path(os.environ.get("DATA_DIR", "data"))
    PROJECTS = DATA_DIR / "projects"
    API_KEY = os.environ.get("API_KEY", "")
    # Server-side folder imports: case folders placed here (host ./inbox, mounted
    # read-only in Docker) can be imported into a project with one click.
    INBOX_DIR = Path(os.environ.get("INBOX_DIR", "inbox"))
    # Where the LangGraph SQLite checkpoint DB is *worked on* when DATA_DIR is a network
    # or FUSE mount (Cloud Run + GCS: no POSIX locks, random writes unsupported — SQLite
    # there is unsafe). Unset = the DB lives in the project's work/ dir directly.
    GRAPH_DB_SCRATCH = os.environ.get("GRAPH_DB_SCRATCH_DIR")


configure()


# ---------------------------------------------------------------- auth

def _key_ok(candidate: str | None) -> bool:
    return bool(candidate) and secrets.compare_digest(candidate, API_KEY)


def require_key(x_api_key: str | None = Header(default=None)) -> None:
    if API_KEY and not _key_ok(x_api_key):
        raise HTTPException(401, "invalid or missing X-API-Key header")


def require_key_or_query(x_api_key: str | None = Header(default=None),
                         key: str | None = None) -> None:
    """Evidence page images are also opened as plain browser links (new tab), which
    cannot send headers — those endpoints accept the key as ?key=… too."""
    if API_KEY and not (_key_ok(x_api_key) or _key_ok(key)):
        raise HTTPException(401, "invalid or missing X-API-Key header")


def acting_user(x_user: str | None = Header(default=None)) -> str:
    """Who is acting, from the X-User header until per-user sessions arrive (checklist B9)."""
    return (x_user or "").strip() or DEFAULT_USER


# ---------------------------------------------------------------- the job runner (Postgres)

def runner():
    """The JobRunner over the Postgres queue, or 503 when DATABASE_URL is not set (the
    routes that only touch project files keep working without it)."""
    global _runner
    from backend.errors import ApiError
    if not os.environ.get("DATABASE_URL"):
        raise ApiError(503, "queue_unavailable", "DATABASE_URL is not set; the check worker needs Postgres")
    if _runner is None:
        import app.checks.vendor_check  # noqa: F401  registers the pipeline (decide) for this process
        from app.jobs.runner import JobRunner
        _runner = JobRunner().open()
    return _runner


def reset_runner() -> None:
    global _runner
    if _runner is not None:
        try:
            _runner.close()
        except Exception:   # noqa: BLE001
            pass
    _runner = None


# ---------------------------------------------------------------- files and project state

def _read_json(path: Path) -> dict:
    return json.loads(path.read_text())


def _write_json(path: Path, obj) -> None:
    """Atomic write (temp file + rename): status.json is rewritten on every progress
    line by background jobs while the UI/tests poll it — a reader must never see a
    half-written file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    tmp.write_text(json.dumps(obj, indent=2, ensure_ascii=False))
    os.replace(tmp, path)


# Ids are generated by create_project as <slug>-<hex>; anything else ('..', a path)
# is refused before it can touch the filesystem — '..' would resolve to DATA_DIR itself.
PID_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,60}$")


def _project_dir(pid: str) -> Path:
    pdir = PROJECTS / pid
    if not PID_RE.fullmatch(pid) or not pdir.is_dir():
        raise HTTPException(404, f"project '{pid}' not found")
    return pdir


def _set_status(pdir: Path, state: str, detail: str = "") -> None:
    _write_json(pdir / "status.json", {"state": state, "detail": detail, "updated": time.time()})


def _get_status(pdir: Path) -> dict:
    path = pdir / "status.json"
    return _read_json(path) if path.is_file() else {"state": "idle", "detail": ""}


def data_class_of(pdir: Path) -> str:
    meta = _read_json(pdir / "meta.json") if (pdir / "meta.json").is_file() else {}
    if meta.get("data_class"):
        return meta["data_class"]
    return "synthetic" if meta.get("synthetic") else "confidential"


def doc_id(rel_path: str) -> str:
    """A stable id for a document: the first 12 hex digits of the sha1 of its path
    relative to the project (e.g. 'bids/Tenderer_B/offer.pdf')."""
    import hashlib
    return hashlib.sha1(rel_path.encode()).hexdigest()[:12]


def documents_of(pdir: Path) -> list[dict]:
    """Every PDF of the project: tender documents, then each tenderer's offer files."""
    out = []
    for path in sorted((pdir / "tender").glob("*.pdf")) if (pdir / "tender").is_dir() else []:
        rel = f"tender/{path.name}"
        out.append({"doc_id": doc_id(rel), "rel": rel, "path": path, "file": path.name, "kind": "tender", "tenderer": None})
    for folder in sorted(p for p in (pdir / "bids").iterdir() if p.is_dir()) if (pdir / "bids").is_dir() else []:
        for path in sorted(p for p in folder.rglob("*.pdf") if not p.name.startswith("~$")):
            rel = f"bids/{folder.name}/{path.relative_to(folder)}"
            out.append({"doc_id": doc_id(rel), "rel": rel, "path": path, "file": path.name, "kind": "bid",
                        "tenderer": folder.name})
    return out


def find_document(pdir: Path, wanted: str) -> dict:
    for d in documents_of(pdir):
        if d["doc_id"] == wanted:
            return d
    raise HTTPException(404, f"document '{wanted}' not found")


def _make_cfg(pdir: Path) -> Config:
    cfg = Config()
    cfg.cache_dir = pdir / "work" / "cache"
    cfg.max_ocr_pages = int(os.environ.get("MAX_OCR_PAGES", cfg.max_ocr_pages))
    return cfg


def _safe_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._ -]+", "_", Path(name).name).strip()
    if not cleaned:
        raise HTTPException(400, f"unusable filename: {name!r}")
    return cleaned


async def _save_pdfs(files: list[UploadFile], dest: Path) -> list[str]:
    dest.mkdir(parents=True, exist_ok=True)
    saved = []
    for f in files:
        name = _safe_name(f.filename or "")
        if not name.lower().endswith(".pdf"):
            raise HTTPException(400, f"only PDF uploads are accepted, got: {name}")
        (dest / name).write_bytes(await f.read())
        saved.append(name)
    return saved


def _bidder_names(pdir: Path) -> set[str]:
    uploaded = {p.name for p in (pdir / "bids").iterdir() if p.is_dir()}
    extracted = {p.stem for p in (pdir / "work" / "bids").glob("*.json")}
    return uploaded | extracted


def _require_rubric(pdir: Path) -> Path:
    rubric_path = pdir / "work" / "rubric.json"
    if not rubric_path.is_file():
        raise HTTPException(400, "derive (and review) the rubric first")
    return rubric_path


def _stored_extractions(pdir: Path) -> list[BidExtraction]:
    """Every bidder's stored extraction (the graph's output, possibly human-corrected)."""
    names = sorted(_bidder_names(pdir))
    missing = [n for n in names if not (pdir / "work" / "bids" / f"{n}.json").is_file()]
    if missing:
        raise HTTPException(400, f"no extraction yet for: {', '.join(missing)} — start the "
                                 "orchestrated run (POST /run) first")
    return [BidExtraction.model_validate(_read_json(pdir / "work" / "bids" / f"{n}.json"))
            for n in names]
